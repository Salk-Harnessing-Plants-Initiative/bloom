-- 20261109120000_add_genome_browser_builds.sql
--
-- The browser-ready copies of a genome version. A genome version is uploaded as a plain-gzip
-- FASTA and GTF, which no genome browser can read: it needs a bgzip-compressed FASTA with its
-- .fai and .gzi, and a position-sorted bgzip GTF with its .tbi, all read by HTTP range
-- request. A browser build is one set of those five files for one ready version, stored at
-- <genome>/v<N>/browser/b<B>/. This row records the folder, the five files' checksums and
-- sizes, the tools used and whether the source GTF had to be sorted. Each build also records
-- where every gene of the GTF sits (genome_genes), readable once the build is ready, for gene
-- search and for links from single-cell genes to the genome. A build is uploading, then ready
-- or abandoned; an admin can withdraw a ready one, with a reason, and a new build of the same
-- version can then be made. A ready build, its files and its genes never change. The build
-- functions and storage rules are added by 20261109120100.
-- Forward-only; rollback in supabase/rollbacks/.

BEGIN;

SET LOCAL lock_timeout = '5s';

-- 1. The five files ------------------------------------------------------------------------

-- Every build holds exactly these five files, under the build's folder. One definition, used
-- by the file record's check, the storage rules and whoever reads a build.
CREATE OR REPLACE FUNCTION public.genome_browser_build_roles()
RETURNS TABLE(role TEXT, basename TEXT)
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
AS $$
    VALUES ('fasta', 'genome.fa.gz'),
           ('fasta_fai', 'genome.fa.gz.fai'),
           ('fasta_gzi', 'genome.fa.gz.gzi'),
           ('gtf', 'genes.gtf.gz'),
           ('gtf_tbi', 'genes.gtf.gz.tbi');
$$;

-- True when `files` holds exactly the five roles, each with a 64-hex SHA-256 and a positive
-- byte count, e.g. {"fasta": {"sha256": "ab..", "bytes": 1234}, ...}.
CREATE OR REPLACE FUNCTION public.genome_browser_files_ok(p_files JSONB)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog, public
AS $$
    SELECT p_files IS NOT NULL
       AND jsonb_typeof(p_files) = 'object'
       AND (SELECT count(*) FROM jsonb_object_keys(p_files)) = 5
       AND NOT EXISTS (
             SELECT 1 FROM public.genome_browser_build_roles() r
              WHERE coalesce(p_files -> r.role ->> 'sha256', '') !~ '^[0-9a-f]{64}$'
                 OR coalesce(p_files -> r.role ->> 'bytes', '') !~ '^[1-9][0-9]*$'
           );
$$;

-- 2. Table ---------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.genome_browser_builds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_id BIGINT NOT NULL,
    -- Numbered per version, from 1.
    build INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'uploading',
    -- The tools used, e.g. {"htslib": "1.21", "pysam": "0.23.0"}.
    tool_versions JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Where the five objects live in the genome-references bucket, set from the genome, version
    -- and build; each object is this folder and the role's basename.
    folder TEXT NOT NULL,
    -- Set when the build is finished: the five roles, each with its SHA-256 and size.
    files JSONB,
    -- Whether the version's GTF had to be position-sorted before indexing.
    gtf_was_sorted BOOLEAN,
    -- Set when the build is finished: how many genes it records.
    gene_count INTEGER,
    created_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ready_at TIMESTAMPTZ,
    withdrawn_reason TEXT,
    withdrawn_at TIMESTAMPTZ
);

-- Each gene of a build, where the GTF places it (1-based, both ends included). A gene's span is
-- its `gene` line, or its exons' span when the GTF has none.
CREATE TABLE IF NOT EXISTS public.genome_genes (
    build_id BIGINT NOT NULL,
    gene_id TEXT NOT NULL,
    gene_name TEXT,
    contig TEXT NOT NULL,
    gene_start BIGINT NOT NULL,
    gene_end BIGINT NOT NULL,
    strand TEXT NOT NULL
);

-- 3. Keys ----------------------------------------------------------------------------------

DO $$
DECLARE
  v_key RECORD;
  existing TEXT;
BEGIN
  FOR v_key IN
    SELECT * FROM (VALUES
      ('genome_browser_builds', 'genome_browser_builds_pkey', 'PRIMARY KEY (id)'),
      ('genome_browser_builds', 'genome_browser_builds_version_build_key',
       'UNIQUE (version_id, build)'),
      ('genome_browser_builds', 'genome_browser_builds_folder_key', 'UNIQUE (folder)'),
      ('genome_genes', 'genome_genes_pkey', 'PRIMARY KEY (build_id, gene_id)'),
      ('genome_genes', 'genome_genes_build_id_fkey',
       'FOREIGN KEY (build_id) REFERENCES genome_browser_builds(id)')
    ) AS k(tbl, name, def)
  LOOP
    SELECT pg_get_constraintdef(c.oid) INTO existing
      FROM pg_constraint c
     WHERE c.conname = v_key.name AND c.conrelid = format('public.%I', v_key.tbl)::regclass;
    IF existing IS NULL THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I %s',
                     v_key.tbl, v_key.name, v_key.def);
    ELSIF existing <> v_key.def THEN
      RAISE EXCEPTION '% is %, expected %', v_key.name, existing, v_key.def;
    END IF;
  END LOOP;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'genome_browser_builds_version_id_fkey'
       AND conrelid = 'public.genome_browser_builds'::regclass
  ) THEN
    ALTER TABLE public.genome_browser_builds ADD CONSTRAINT genome_browser_builds_version_id_fkey
      FOREIGN KEY (version_id) REFERENCES public.genome_reference_versions(id);
  END IF;
END $$;

-- At most one build of a version is being made or in use.
CREATE UNIQUE INDEX IF NOT EXISTS genome_browser_builds_one_live
    ON public.genome_browser_builds (version_id) WHERE status IN ('uploading', 'ready');

-- Single-cell genes are looked up by id; the browser and expression tracks read a region.
CREATE INDEX IF NOT EXISTS genome_genes_gene_id_idx ON public.genome_genes (gene_id);
CREATE INDEX IF NOT EXISTS genome_genes_region_idx
    ON public.genome_genes (build_id, contig, gene_start);
-- Gene search by part of an id or name.
CREATE INDEX IF NOT EXISTS genome_genes_gene_id_trgm
    ON public.genome_genes USING gin (gene_id gin_trgm_ops);
CREATE INDEX IF NOT EXISTS genome_genes_gene_name_trgm
    ON public.genome_genes USING gin (gene_name gin_trgm_ops);

-- 4. Checks --------------------------------------------------------------------------------

ALTER TABLE public.genome_browser_builds
  DROP CONSTRAINT IF EXISTS genome_browser_builds_build_check,
  ADD CONSTRAINT genome_browser_builds_build_check CHECK (build >= 1),
  DROP CONSTRAINT IF EXISTS genome_browser_builds_status_check,
  ADD CONSTRAINT genome_browser_builds_status_check
    CHECK (status IN ('uploading', 'ready', 'abandoned', 'withdrawn')),
  DROP CONSTRAINT IF EXISTS genome_browser_builds_tool_versions_check,
  ADD CONSTRAINT genome_browser_builds_tool_versions_check CHECK (
    jsonb_typeof(tool_versions) = 'object' AND length(tool_versions::text) <= 2000
  ),
  -- A ready or withdrawn build has its five files, whether its GTF was sorted, its gene count
  -- and ready_at; any other build has none of them.
  DROP CONSTRAINT IF EXISTS genome_browser_builds_finished_check,
  ADD CONSTRAINT genome_browser_builds_finished_check CHECK (
    CASE WHEN status IN ('ready', 'withdrawn') THEN
      num_nulls(files, gtf_was_sorted, gene_count, ready_at) = 0
      AND public.genome_browser_files_ok(files) AND gene_count >= 1
    ELSE
      num_nonnulls(files, gtf_was_sorted, gene_count, ready_at) = 0
    END
  ),
  DROP CONSTRAINT IF EXISTS genome_browser_builds_withdrawn_check,
  ADD CONSTRAINT genome_browser_builds_withdrawn_check CHECK (
    CASE WHEN status = 'withdrawn' THEN
      num_nulls(withdrawn_reason, withdrawn_at) = 0 AND btrim(withdrawn_reason) <> ''
      AND length(withdrawn_reason) <= 1000
    ELSE
      num_nonnulls(withdrawn_reason, withdrawn_at) = 0
    END
  );

ALTER TABLE public.genome_genes
  DROP CONSTRAINT IF EXISTS genome_genes_gene_id_check,
  ADD CONSTRAINT genome_genes_gene_id_check
    CHECK (btrim(gene_id) <> '' AND length(gene_id) <= 200),
  DROP CONSTRAINT IF EXISTS genome_genes_gene_name_check,
  ADD CONSTRAINT genome_genes_gene_name_check CHECK (length(gene_name) <= 200),
  DROP CONSTRAINT IF EXISTS genome_genes_contig_check,
  ADD CONSTRAINT genome_genes_contig_check CHECK (btrim(contig) <> '' AND length(contig) <= 200),
  DROP CONSTRAINT IF EXISTS genome_genes_span_check,
  ADD CONSTRAINT genome_genes_span_check CHECK (gene_start >= 1 AND gene_end >= gene_start),
  DROP CONSTRAINT IF EXISTS genome_genes_strand_check,
  ADD CONSTRAINT genome_genes_strand_check CHECK (strand IN ('+', '-', '.'));

-- 5. What may change -----------------------------------------------------------------------

-- A new build gets its version's next number and its folder, starts as uploading, and only for
-- a ready version, whoever inserts it.
CREATE OR REPLACE FUNCTION public.genome_browser_builds_number()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_status TEXT;
    v_genome TEXT;
    v_version INTEGER;
BEGIN
    IF NEW.status IS DISTINCT FROM 'uploading' THEN
        RAISE EXCEPTION 'a browser build starts as uploading' USING ERRCODE = '55000';
    END IF;
    -- The version's row lock numbers concurrent builds of one version one after another.
    SELECT v.status, g.name, v.version INTO v_status, v_genome, v_version
      FROM public.genome_reference_versions v
      JOIN public.genome_references g ON g.id = v.genome_id
     WHERE v.id = NEW.version_id
       FOR UPDATE OF v;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'no genome version %', NEW.version_id USING ERRCODE = '23503';
    END IF;
    IF v_status <> 'ready' THEN
        RAISE EXCEPTION 'genome version % is %, not ready', NEW.version_id, v_status
            USING ERRCODE = '55000';
    END IF;
    SELECT coalesce(max(b.build), 0) + 1 INTO NEW.build
      FROM public.genome_browser_builds b
     WHERE b.version_id = NEW.version_id;
    NEW.folder := v_genome || '/v' || v_version || '/browser/b' || NEW.build;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS genome_browser_builds_number ON public.genome_browser_builds;
CREATE TRIGGER genome_browser_builds_number
    BEFORE INSERT ON public.genome_browser_builds
    FOR EACH ROW EXECUTE FUNCTION public.genome_browser_builds_number();

-- A build's identity and folder never change. Its file record, sorted flag, gene count and
-- ready_at are set once, when it is finished. Status moves only uploading -> ready | abandoned and
-- ready -> withdrawn. A ready or withdrawn build cannot be deleted.
CREATE OR REPLACE FUNCTION public.genome_browser_builds_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status IN ('ready', 'withdrawn') THEN
            RAISE EXCEPTION 'browser build % is %; withdraw it instead of deleting it',
                OLD.id, OLD.status USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.version_id IS DISTINCT FROM OLD.version_id
       OR NEW.build IS DISTINCT FROM OLD.build
       OR NEW.tool_versions IS DISTINCT FROM OLD.tool_versions
       OR NEW.folder IS DISTINCT FROM OLD.folder
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'a browser build''s identity cannot change' USING ERRCODE = '55000';
    END IF;

    IF OLD.status <> 'uploading' AND (
        NEW.files IS DISTINCT FROM OLD.files
        OR NEW.gtf_was_sorted IS DISTINCT FROM OLD.gtf_was_sorted
        OR NEW.gene_count IS DISTINCT FROM OLD.gene_count
        OR NEW.ready_at IS DISTINCT FROM OLD.ready_at
    ) THEN
        RAISE EXCEPTION 'browser build % is %; it cannot change', OLD.id, OLD.status
            USING ERRCODE = '55000';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status AND (OLD.status, NEW.status) NOT IN (
        ('uploading', 'ready'), ('uploading', 'abandoned'), ('ready', 'withdrawn')
    ) THEN
        RAISE EXCEPTION 'browser build % cannot go from % to %', OLD.id, OLD.status, NEW.status
            USING ERRCODE = '55000';
    END IF;

    IF NEW.status = 'withdrawn' AND OLD.status = 'ready' THEN
        NEW.withdrawn_at := now();
    ELSIF NEW.withdrawn_reason IS DISTINCT FROM OLD.withdrawn_reason
          OR NEW.withdrawn_at IS DISTINCT FROM OLD.withdrawn_at THEN
        RAISE EXCEPTION 'a withdrawal is recorded only when a ready build is withdrawn'
            USING ERRCODE = '55000';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS genome_browser_builds_guard ON public.genome_browser_builds;
CREATE TRIGGER genome_browser_builds_guard
    BEFORE UPDATE OR DELETE ON public.genome_browser_builds
    FOR EACH ROW EXECUTE FUNCTION public.genome_browser_builds_guard();

-- A build's genes are added or removed only while it is uploading, for bloom_admin too, and a
-- gene row is never edited.
CREATE OR REPLACE FUNCTION public.genome_genes_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_build_id BIGINT := CASE WHEN TG_OP = 'INSERT' THEN NEW.build_id ELSE OLD.build_id END;
    v_status TEXT;
BEGIN
    SELECT b.status INTO v_status FROM public.genome_browser_builds b WHERE b.id = v_build_id;
    IF TG_OP = 'UPDATE' OR v_status IS DISTINCT FROM 'uploading' THEN
        RAISE EXCEPTION 'browser build % is %; its genes cannot change', v_build_id,
            coalesce(v_status, 'missing') USING ERRCODE = '55000';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS genome_genes_guard ON public.genome_genes;
CREATE TRIGGER genome_genes_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.genome_genes
    FOR EACH ROW EXECUTE FUNCTION public.genome_genes_guard();

