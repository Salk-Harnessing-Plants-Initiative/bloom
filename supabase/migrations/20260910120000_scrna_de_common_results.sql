-- Make scrna_de the one table for every pairwise differential expression result.
--
-- Two producers are arriving: an analysis run outside Bloom and loaded by an
-- operator, and a comparison a scientist asks for in the browser. They were
-- heading for two tables of the same shape. scrna_de already carries the
-- dataset, the cell type, both compared groups, their sizes and five counts --
-- everything the second table was going to hold, minus which analysis produced
-- the row. So this extends it rather than building its twin.
--
-- Three things are added:
--
--   1. Which analysis produced a row, so a dataset can hold more than one
--      answer to the same question instead of the newest overwriting the last.
--   2. What kind of thing the two groups are. The batch export compares
--      genotypes within a cell type; the browser compares cell types across the
--      dataset. Both are "group1 against group2" and they resolve against
--      different tables, so a reader has to be told which.
--   3. The per-gene outcome as rows. It lives in a storage object today, which
--      means the counts and the genes behind them are in different places and
--      can disagree -- and that ranking genes, or following one gene across
--      comparisons, needs every object downloaded first.
--
-- No column is dropped and no existing row is touched. The one-vs-rest rows
-- that predate contrasts keep their file_path and take no run; every rule below
-- is written so they stay legal exactly as they are.

BEGIN;

-- 1. The analysis --------------------------------------------------------------
-- One row per analysis, whichever route produced it. A batch upload is a run
-- that completes on arrival; a dispatched job passes through the queue. Sharing
-- one table is what lets a reader ask "where did this result come from" without
-- knowing which route to ask.

CREATE TABLE IF NOT EXISTS public.scrna_de_runs (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    dataset_id BIGINT NOT NULL REFERENCES public.scrna_datasets(id),
    source TEXT NOT NULL
        CHECK (source IN ('batch', 'ondemand')),
    status TEXT NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'submitted', 'running', 'complete', 'failed')),
    method TEXT NOT NULL,
    params JSONB NOT NULL DEFAULT '{}'::jsonb,
    params_hash TEXT NOT NULL,
    -- Attribution only. Deliberately NOT a visibility filter: scrna_* is shared
    -- scientific data and every reader role sees every run.
    requested_by UUID,
    argo_workflow_name TEXT,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    submitted_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    -- A batch upload never reaches Argo and never queues. Saying so here keeps
    -- the two routes from having to be told apart by a NULL somewhere else.
    CONSTRAINT scrna_de_runs_batch_does_not_dispatch
        CHECK (source <> 'batch' OR argo_workflow_name IS NULL),
    CONSTRAINT scrna_de_runs_failed_says_why
        CHECK (status <> 'failed' OR error_message IS NOT NULL),
    CONSTRAINT scrna_de_runs_finished_has_a_time
        CHECK (status NOT IN ('complete', 'failed') OR completed_at IS NOT NULL)
);

ALTER TABLE public.scrna_de_runs ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.scrna_de_runs IS
  'One row per differential expression analysis. source says how it arrived: '
  '''batch'' for an analysis computed elsewhere and loaded, ''ondemand'' for one '
  'this platform ran.';
COMMENT ON COLUMN public.scrna_de_runs.params_hash IS
  'Identifies the question asked. Two runs with the same dataset, groups, method '
  'and hash answer the same question and one may stand in for the other.';

-- The poller's sweep predicate: every run still in flight.
CREATE INDEX IF NOT EXISTS scrna_de_runs_active_idx
    ON public.scrna_de_runs (status)
    WHERE status IN ('submitted', 'running');

-- Finding the analyses a dataset holds, newest first.
CREATE INDEX IF NOT EXISTS scrna_de_runs_dataset_idx
    ON public.scrna_de_runs (dataset_id, created_at DESC);

-- 2. What scrna_de gains -------------------------------------------------------

ALTER TABLE public.scrna_de
  ADD COLUMN IF NOT EXISTS run_id      BIGINT REFERENCES public.scrna_de_runs(id),
  ADD COLUMN IF NOT EXISTS group_kind  TEXT    DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS method      TEXT    DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS params_hash TEXT    DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS tested      BOOLEAN DEFAULT NULL;

COMMENT ON COLUMN public.scrna_de.run_id IS
  'The analysis that produced this row. NULL means it predates runs: the '
  'one-vs-rest markers uploaded by hand, which are kept as they are.';
COMMENT ON COLUMN public.scrna_de.group_kind IS
  '''cluster'' when group1/group2 name cell types, ''genotype'' when they name '
  'rows of scrna_genotypes. NULL only for the pre-run rows.';
COMMENT ON COLUMN public.scrna_de.tested IS
  'False for a comparison that was considered and never run -- too few cells on '
  'one side, usually. Such a row carries its group sizes, which is what explains '
  'why, and no gene rows.';

-- 3. The rule that assumed a file ----------------------------------------------
-- The old rule read: a row either names a file, or it names a contrast and
-- tested nothing. That was true while every result was an object. A result whose
-- genes are rows names no file and has tested plenty, so the rule has to become
-- about where the result lives rather than whether a path is set.

ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_no_file_means_nothing_tested;

-- NOT VALID on purpose. A table that already holds contrast rows written before
-- runs existed has some with neither a file nor a run -- a comparison that was
-- considered and never tested had nothing to point at and nothing to belong to.
-- Those are left as found; every row written from here on has a run.
ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_result_is_somewhere;
ALTER TABLE public.scrna_de
  ADD CONSTRAINT scrna_de_result_is_somewhere
  CHECK (run_id IS NOT NULL OR file_path IS NOT NULL)
  NOT VALID;

COMMENT ON CONSTRAINT scrna_de_result_is_somewhere ON public.scrna_de IS
  'Every row is reachable: a pre-run row through the object it names, a run row '
  'through its gene rows. A row that is neither describes nothing.';

-- A comparison that was never run has nothing to count and nothing to show.
ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_untested_counted_nothing;
ALTER TABLE public.scrna_de
  ADD CONSTRAINT scrna_de_untested_counted_nothing
  CHECK (tested IS NOT FALSE OR COALESCE(n_genes_tested, 0) = 0);

-- 4. What a run row must say ---------------------------------------------------
-- All of these are conditioned on run_id, so a pre-run row satisfies every one
-- of them without carrying any of the new columns.

ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_run_rows_are_complete;
ALTER TABLE public.scrna_de
  ADD CONSTRAINT scrna_de_run_rows_are_complete
  CHECK (
    run_id IS NULL
    OR (group_kind IS NOT NULL
        AND method IS NOT NULL
        AND params_hash IS NOT NULL
        AND tested IS NOT NULL)
  );

ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_group_kind_known;
ALTER TABLE public.scrna_de
  ADD CONSTRAINT scrna_de_group_kind_known
  CHECK (group_kind IS NULL OR group_kind IN ('cluster', 'genotype'));

-- 5. The cell type is one the dataset has --------------------------------------
-- Every other table naming a cell type carries this foreign key -- scrna_cells,
-- scrna_cluster_stats, scrna_cluster_neighbors. scrna_de is the one that names
-- one in free text, which is why a loader has had to check it in Python.
--
-- NOT VALID on purpose: a pre-run row may name a cell type the catalogue has
-- since lost, and that is not this migration's to resolve. New rows are checked
-- from here on. MATCH SIMPLE means a NULL cluster_id -- a comparison across the
-- whole dataset -- skips the check, which is the intent.

ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_cluster_in_catalogue;
ALTER TABLE public.scrna_de
  ADD CONSTRAINT scrna_de_cluster_in_catalogue
  FOREIGN KEY (dataset_id, cluster_id)
  REFERENCES public.scrna_clusters (dataset_id, cluster_id)
  -- Matching scrna_cells: a rename follows, because relabelling a cell type does
  -- not invalidate a result about it; a delete is refused, because the result is
  -- about that cell type and removing it out from under one is the thing worth
  -- preventing. The cell loader already refuses that case in Python; this is the
  -- same rule where the database can enforce it.
  ON UPDATE CASCADE ON DELETE RESTRICT
  NOT VALID;

-- 6. One row per comparison, per analysis --------------------------------------
-- Was (dataset_id, cluster_id, contrast), which allowed a dataset exactly one
-- answer per question. Adding the run is what lets a second analysis stand
-- beside the first instead of replacing it.

ALTER TABLE public.scrna_de
  DROP CONSTRAINT IF EXISTS scrna_de_comparison_uniqueness;
ALTER TABLE public.scrna_de
  ADD CONSTRAINT scrna_de_comparison_uniqueness
  UNIQUE NULLS NOT DISTINCT (dataset_id, run_id, cluster_id, contrast);

-- Reading one analysis, and finding the analyses that answer a question.
CREATE INDEX IF NOT EXISTS scrna_de_run_idx
    ON public.scrna_de (run_id);
CREATE INDEX IF NOT EXISTS scrna_de_question_idx
    ON public.scrna_de (dataset_id, cluster_id, group1, group2, params_hash);

-- 7. Genes are rows ------------------------------------------------------------
-- scrna_genes has no unique key on (dataset_id, id), so it cannot be the target
-- of the composite foreign key below. Its primary key already makes this
-- redundant for uniqueness; it exists so the reference can be declared.

-- The one constraint here not added by DROP IF EXISTS then ADD. That idiom is
-- for CHECKs, which own nothing and are always free to drop. This one owns an
-- index that the foreign key below points at, so a second run cannot drop it --
-- and dropping it would rebuild the index and re-validate the foreign key over
-- every gene row, which is the largest table in this schema.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
     WHERE conname = 'scrna_genes_dataset_gene_key'
       AND conrelid = 'public.scrna_genes'::regclass
  ) THEN
    ALTER TABLE public.scrna_genes
      ADD CONSTRAINT scrna_genes_dataset_gene_key UNIQUE (dataset_id, id);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.scrna_de_genes (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    de_id BIGINT NOT NULL REFERENCES public.scrna_de(id) ON DELETE CASCADE,
    -- Carried so the gene can be tied to the same dataset as the result. On its
    -- own, gene_id would let a result reference another dataset's genes.
    dataset_id BIGINT NOT NULL,
    gene_id BIGINT NOT NULL,
    log2fc REAL NOT NULL,
    pvalue DOUBLE PRECISION NOT NULL,
    fdr DOUBLE PRECISION NOT NULL,
    pct_1 REAL,
    pct_2 REAL,
    direction TEXT NOT NULL
        CHECK (direction IN ('up', 'down')),
    CONSTRAINT scrna_de_genes_one_row_per_gene UNIQUE (de_id, gene_id),
    CONSTRAINT scrna_de_genes_gene_belongs_to_dataset
        FOREIGN KEY (dataset_id, gene_id)
        REFERENCES public.scrna_genes (dataset_id, id),
    -- A p-value outside [0,1] means the file was misread, not that the gene is
    -- remarkable. Same for the proportion of cells expressing it.
    CONSTRAINT scrna_de_genes_probabilities_are_probabilities
        CHECK (pvalue >= 0 AND pvalue <= 1 AND fdr >= 0 AND fdr <= 1),
    CONSTRAINT scrna_de_genes_proportions_are_proportions
        CHECK ((pct_1 IS NULL OR (pct_1 >= 0 AND pct_1 <= 1))
           AND (pct_2 IS NULL OR (pct_2 >= 0 AND pct_2 <= 1))),
    -- Correction only ever raises a p-value.
    CONSTRAINT scrna_de_genes_fdr_is_not_below_pvalue
        CHECK (fdr >= pvalue),
    -- direction is derived from the fold change and must not contradict it.
    CONSTRAINT scrna_de_genes_direction_matches_fold_change
        CHECK ((direction = 'up' AND log2fc > 0) OR (direction = 'down' AND log2fc <= 0))
);

ALTER TABLE public.scrna_de_genes ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.scrna_de_genes IS
  'One row per gene per comparison. Rows rather than a stored file so that genes '
  'can be ranked, cut at a threshold chosen when the question is asked, and '
  'followed across comparisons -- and so the counts on scrna_de describe '
  'something the database can check.';
COMMENT ON COLUMN public.scrna_de_genes.direction IS
  'Which side of the comparison the gene is higher in. A fold change of exactly '
  'zero counts as down, so up and down together account for every row.';

-- Ranking within one comparison: the panel's first query.
CREATE INDEX IF NOT EXISTS scrna_de_genes_ranking_idx
    ON public.scrna_de_genes (de_id, fdr);

-- Following one gene across every comparison of a dataset.
CREATE INDEX IF NOT EXISTS scrna_de_genes_gene_idx
    ON public.scrna_de_genes (dataset_id, gene_id);

-- 8. Access --------------------------------------------------------------------
-- Matches scrna_de: bloom_admin writes, the reader roles read. Grants come from
-- the role migrations; re-stating them here would undo later narrowing.
--
-- No anon policy, deliberately. scrna_de carries one from 2026-01, and these
-- tables hold the same results at finer grain plus who asked for them. Widening
-- that to unauthenticated readers is a decision to take on its own, not one to
-- inherit by matching a neighbouring table.

DROP POLICY IF EXISTS admin_all_scrna_de_runs ON public.scrna_de_runs;
CREATE POLICY admin_all_scrna_de_runs
  ON public.scrna_de_runs FOR ALL TO bloom_admin USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS agent_read_scrna_de_runs ON public.scrna_de_runs;
CREATE POLICY agent_read_scrna_de_runs
  ON public.scrna_de_runs FOR SELECT TO bloom_agent USING (true);

DROP POLICY IF EXISTS user_read_scrna_de_runs ON public.scrna_de_runs;
CREATE POLICY user_read_scrna_de_runs
  ON public.scrna_de_runs FOR SELECT TO bloom_user USING (true);

DROP POLICY IF EXISTS admin_all_scrna_de_genes ON public.scrna_de_genes;
CREATE POLICY admin_all_scrna_de_genes
  ON public.scrna_de_genes FOR ALL TO bloom_admin USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS agent_read_scrna_de_genes ON public.scrna_de_genes;
CREATE POLICY agent_read_scrna_de_genes
  ON public.scrna_de_genes FOR SELECT TO bloom_agent USING (true);

DROP POLICY IF EXISTS user_read_scrna_de_genes ON public.scrna_de_genes;
CREATE POLICY user_read_scrna_de_genes
  ON public.scrna_de_genes FOR SELECT TO bloom_user USING (true);

COMMIT;
