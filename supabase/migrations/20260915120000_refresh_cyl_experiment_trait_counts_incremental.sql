-- Refresh cyl_experiment_trait_counts incrementally, inside the database, with pg_cron (bloom#831).
--
-- The GitHub Action calls refresh_cyl_experiment_trait_counts() through PostgREST, where the
-- authenticator role's 8 s statement_timeout cancels the full recount every time. This migration:
--   1. enables pg_cron (preloaded in the supabase/postgres image);
--   2. adds cyl_experiment_trait_count_changes, an insert-only log of experiments whose
--      latest-source trait data changed, appended by triggers on cyl_scan_latest_source;
--   3. adds refresh_changed_cyl_experiment_trait_counts(), which recounts only logged experiments;
--   4. seeds the log with every experiment, so the first scheduled run does the full fill;
--   5. schedules that function nightly at 06:00 UTC, run as `postgres` (not a superuser) over
--      pg_cron's own connection, so no API timeout applies.
-- refresh_cyl_experiment_trait_counts() is unchanged and remains the manual full refresh.
--
-- Manual rollback: supabase/rollbacks/20260915120000_refresh_cyl_experiment_trait_counts_incremental_rollback.sql

BEGIN;

CREATE EXTENSION IF NOT EXISTS pg_cron;

-- No unique constraint: concurrent saves never wait on each other's row.
CREATE TABLE IF NOT EXISTS public.cyl_experiment_trait_count_changes (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id bigint NOT NULL REFERENCES public.cyl_experiments(id) ON DELETE CASCADE,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- Internal bookkeeping: only the SECURITY DEFINER functions below read or write it.
ALTER TABLE public.cyl_experiment_trait_count_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cyl_experiment_trait_count_changes
    FROM PUBLIC, anon, authenticated, service_role,
         bloom_admin, bloom_agent, bloom_user, bloom_writer;

CREATE OR REPLACE FUNCTION public.mark_cyl_experiment_trait_count_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_scan_id bigint := coalesce(NEW.scan_id, OLD.scan_id);
BEGIN
    -- Only scans that belong to an experiment are logged: a wave may have no experiment, and a
    -- scan already removed by a cascade resolves to none.
    INSERT INTO public.cyl_experiment_trait_count_changes (experiment_id)
    SELECT w.experiment_id
    FROM public.cyl_scans  s
    JOIN public.cyl_plants p ON p.id = s.plant_id
    JOIN public.cyl_waves  w ON w.id = p.wave_id
    WHERE s.id = v_scan_id
      AND w.experiment_id IS NOT NULL;
    RETURN NULL;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.mark_cyl_experiment_trait_count_change()
    FROM PUBLIC, anon, authenticated, service_role;

-- Fires once per scan per new result: later trait rows of the same result re-upsert the same
-- max_source_id, which the WHEN clause skips.
CREATE OR REPLACE TRIGGER mark_cyl_experiment_trait_count_change_on_insert_delete
    AFTER INSERT OR DELETE ON public.cyl_scan_latest_source
    FOR EACH ROW
    EXECUTE FUNCTION public.mark_cyl_experiment_trait_count_change();

CREATE OR REPLACE TRIGGER mark_cyl_experiment_trait_count_change_on_update
    AFTER UPDATE ON public.cyl_scan_latest_source
    FOR EACH ROW
    WHEN (OLD.max_source_id IS DISTINCT FROM NEW.max_source_id)
    EXECUTE FUNCTION public.mark_cyl_experiment_trait_count_change();

CREATE OR REPLACE FUNCTION public.refresh_changed_cyl_experiment_trait_counts()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pg_temp
AS $$
DECLARE
    v_experiment_ids bigint[];
BEGIN
    -- Same lock as the full refresh, so the two never overlap.
    PERFORM pg_advisory_xact_lock(0, hashtext('refresh_cyl_experiment_trait_counts'));

    -- Rows from saves not yet committed are invisible here, so they stay for the next run.
    WITH consumed AS (
        DELETE FROM public.cyl_experiment_trait_count_changes WHERE true
        RETURNING experiment_id
    )
    SELECT array_agg(DISTINCT experiment_id) INTO v_experiment_ids FROM consumed;

    IF v_experiment_ids IS NOT NULL THEN
        DELETE FROM public.cyl_experiment_trait_counts
        WHERE experiment_id = ANY (v_experiment_ids);

        -- The full refresh's query, limited to the logged experiments.
        INSERT INTO public.cyl_experiment_trait_counts (experiment_id, n_traits, updated_at)
        SELECT d.experiment_id, count(*), now()
        FROM (
            SELECT DISTINCT w.experiment_id, cst.trait_id
            FROM public.cyl_waves              w
            JOIN public.cyl_plants             p   ON p.wave_id = w.id AND p.accession_id IS NOT NULL
            JOIN public.cyl_scans              s   ON s.plant_id = p.id
            JOIN public.cyl_scan_traits        cst ON cst.scan_id = s.id
            JOIN public.cyl_scan_latest_source l   ON l.scan_id = cst.scan_id
                AND cst.source_id IS NOT DISTINCT FROM l.max_source_id
            WHERE cst.trait_id IS NOT NULL
              AND w.experiment_id = ANY (v_experiment_ids)
        ) d
        GROUP BY d.experiment_id;
    END IF;

    -- Unlogged experiments had no latest-source change, so every row is current as of this run.
    UPDATE public.cyl_experiment_trait_counts SET updated_at = now() WHERE true;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.refresh_changed_cyl_experiment_trait_counts()
    FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.refresh_changed_cyl_experiment_trait_counts() TO postgres;

-- The first scheduled run recounts every experiment.
INSERT INTO public.cyl_experiment_trait_count_changes (experiment_id)
SELECT id FROM public.cyl_experiments;

-- The job runs as postgres. `supabase db push` applies migrations as postgres, where cron.schedule
-- already owns the job as postgres; a superuser apply has to name postgres explicitly. Scheduling
-- the same job name for the same user updates the job, so re-applying keeps one.
DO $$
DECLARE
    v_command constant text :=
        $cmd$SET statement_timeout = '5min'; SELECT public.refresh_changed_cyl_experiment_trait_counts()$cmd$;
BEGIN
    IF (SELECT rolsuper FROM pg_roles WHERE rolname = current_user) THEN
        PERFORM cron.schedule_in_database(
            'refresh-cyl-experiment-trait-counts', '0 6 * * *', v_command, current_database(), 'postgres'
        );
    ELSIF current_user = 'postgres' THEN
        PERFORM cron.schedule('refresh-cyl-experiment-trait-counts', '0 6 * * *', v_command);
    ELSE
        RAISE EXCEPTION 'apply this migration as postgres or a superuser, not %', current_user;
    END IF;
END;
$$;

COMMIT;
