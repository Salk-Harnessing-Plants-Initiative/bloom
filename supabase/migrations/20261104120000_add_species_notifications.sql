-- 20261104120000_add_species_notifications.sql
--
-- What the new-species email needs:
--
-- 1. notification_recipients: who gets Bloom's team notifications, each with a description.
--    Admins add and remove people; the workflows service reads it; no other role can see it.
--    No rows are added here: the first recipients are added by hand in each environment.
-- 2. species.team_notified_at: when the Bloom team was emailed about a new species, so its
--    image can be added. The workflows service sets it before sending, and only on a species
--    that has none, so each species is emailed about at most once. Species already in Bloom
--    are marked when the column is added, so they are never emailed about.
-- Forward-only; rollback in supabase/rollbacks/.

BEGIN;

-- 1. notification_recipients ---------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.notification_recipients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    description TEXT NOT NULL CHECK (btrim(description) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per address, in any casing.
CREATE UNIQUE INDEX IF NOT EXISTS notification_recipients_email_key
    ON public.notification_recipients (lower(email));

ALTER TABLE public.notification_recipients ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS admin_all_notification_recipients ON public.notification_recipients;
CREATE POLICY admin_all_notification_recipients ON public.notification_recipients
    FOR ALL TO bloom_admin USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS workflows_read_notification_recipients ON public.notification_recipients;
CREATE POLICY workflows_read_notification_recipients ON public.notification_recipients
    FOR SELECT TO bloom_workflows USING (true);

REVOKE ALL ON public.notification_recipients
    FROM PUBLIC, anon, authenticated, bloom_user, bloom_agent, bloom_writer, bloom_workflows;
GRANT SELECT ON public.notification_recipients TO bloom_workflows;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.notification_recipients TO bloom_admin;

-- 2. species.team_notified_at --------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'species' AND column_name = 'team_notified_at'
    ) THEN
        ALTER TABLE public.species ADD COLUMN team_notified_at TIMESTAMPTZ;
        -- Only when the column is new: a re-run must not mark species added since.
        UPDATE public.species SET team_notified_at = now();
    END IF;
END$$;

-- The workflows service may set this column only, on a species not yet emailed about.
GRANT UPDATE (team_notified_at) ON public.species TO bloom_workflows;

DROP POLICY IF EXISTS workflows_mark_species_notified ON public.species;
CREATE POLICY workflows_mark_species_notified ON public.species FOR UPDATE TO bloom_workflows
    USING (team_notified_at IS NULL AND deleted_at IS NULL)
    WITH CHECK (team_notified_at IS NOT NULL);

-- PostgREST serves tables from a cached schema.
NOTIFY pgrst, 'reload schema';

COMMIT;
