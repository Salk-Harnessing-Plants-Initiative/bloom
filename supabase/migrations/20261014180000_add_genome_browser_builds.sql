-- 20261014180000_add_genome_browser_builds.sql
--
-- Genome browser builds of each genome version, and where each gene sits on its genome. A
-- build is a block-gzipped FASTA with its .fai and .gzi indexes and a sorted, block-gzipped
-- GFF3 with its .tbi index, under <genome>/v<N>/browser/b<B>/ in the genome-references bucket
-- (the upload functions and storage rules are added by 20261014180100). A build is uploading,
-- then ready or abandoned; an admin can withdraw a ready one, with a reason, and a new build
-- can then be made. A ready build's files and genes never change.
-- Forward-only; rollback in supabase/rollbacks/.

BEGIN;

-- 1. Tables --------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.genome_browser_builds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_id BIGINT NOT NULL,
    -- Numbered per genome version, from 1; a rebuild gets the next number and its own folder.
    build INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'uploading',
    -- The tools that made the files, e.g. {"bgzip": "1.21", "samtools": "1.21"}.
    tool_versions JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Set when the build is finished.
    gene_count INTEGER,
    created_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ready_at TIMESTAMPTZ,
    withdrawn_reason TEXT,
    withdrawn_at TIMESTAMPTZ
);

-- One row per file of a build; the checksum and size are set when the build is finished.
CREATE TABLE IF NOT EXISTS public.genome_browser_objects (
    build_id BIGINT NOT NULL,
    kind TEXT NOT NULL,
    path TEXT NOT NULL,
    sha256 TEXT,
    bytes BIGINT
);

-- Each gene of a build, at its position in the GTF (1-based, both ends included).
CREATE TABLE IF NOT EXISTS public.genome_genes (
    build_id BIGINT NOT NULL,
    gene_id TEXT NOT NULL,
    gene_name TEXT,
    seqid TEXT NOT NULL,
    gene_start BIGINT NOT NULL,
    gene_end BIGINT NOT NULL,
    strand TEXT NOT NULL
);

-- 2. Keys ----------------------------------------------------------------------------------

DO $$
DECLARE
  v_key RECORD;
  existing TEXT;
BEGIN
  FOR v_key IN
    SELECT * FROM (VALUES
      ('genome_browser_builds', 'genome_browser_builds_pkey', 'PRIMARY KEY (id)'),
      ('genome_browser_builds', 'genome_browser_builds_version_build_key',
       'UNIQUE (version_id, build)'),
      ('genome_browser_objects', 'genome_browser_objects_pkey', 'PRIMARY KEY (build_id, kind)'),
      ('genome_browser_objects', 'genome_browser_objects_path_key', 'UNIQUE (path)'),
      ('genome_genes', 'genome_genes_pkey', 'PRIMARY KEY (build_id, gene_id)')
    ) AS k(tbl, name, def)
  LOOP
    SELECT pg_get_constraintdef(c.oid) INTO existing
      FROM pg_constraint c
     WHERE c.conname = v_key.name AND c.conrelid = format('public.%I', v_key.tbl)::regclass;
    IF existing IS NULL THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I %s', v_key.tbl, v_key.name, v_key.def);
    ELSIF existing <> v_key.def THEN
      RAISE EXCEPTION '% is %, expected %', v_key.name, existing, v_key.def;
    END IF;
  END LOOP;
END $$;

DO $$
DECLARE
  v_fk RECORD;
BEGIN
  FOR v_fk IN
    SELECT * FROM (VALUES
      ('genome_browser_builds', 'genome_browser_builds_version_id_fkey',
       'FOREIGN KEY (version_id) REFERENCES public.genome_reference_versions(id)'),
      ('genome_browser_objects', 'genome_browser_objects_build_id_fkey',
       'FOREIGN KEY (build_id) REFERENCES public.genome_browser_builds(id)'),
      ('genome_genes', 'genome_genes_build_id_fkey',
       'FOREIGN KEY (build_id) REFERENCES public.genome_browser_builds(id)')
    ) AS k(tbl, name, def)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c
       WHERE c.conname = v_fk.name AND c.conrelid = format('public.%I', v_fk.tbl)::regclass
    ) THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I %s', v_fk.tbl, v_fk.name, v_fk.def);
    END IF;
  END LOOP;
END $$;

-- At most one build of a version is being made or in use.
CREATE UNIQUE INDEX IF NOT EXISTS genome_browser_builds_one_live_per_version
    ON public.genome_browser_builds (version_id) WHERE status IN ('uploading', 'ready');

-- Single-cell gene lists look genes up by id.
CREATE INDEX IF NOT EXISTS genome_genes_gene_id_idx ON public.genome_genes (gene_id);

-- 3. Checks --------------------------------------------------------------------------------

ALTER TABLE public.genome_browser_builds
  DROP CONSTRAINT IF EXISTS genome_browser_builds_build_check,
  ADD CONSTRAINT genome_browser_builds_build_check CHECK (build >= 1),
  DROP CONSTRAINT IF EXISTS genome_browser_builds_status_check,
  ADD CONSTRAINT genome_browser_builds_status_check
    CHECK (status IN ('uploading', 'ready', 'abandoned', 'withdrawn')),
  DROP CONSTRAINT IF EXISTS genome_browser_builds_tool_versions_check,
  ADD CONSTRAINT genome_browser_builds_tool_versions_check CHECK (
    jsonb_typeof(tool_versions) = 'object' AND length(tool_versions::text) <= 2000
  ),
  -- A ready or withdrawn build has its gene count and ready_at; any other has neither.
  DROP CONSTRAINT IF EXISTS genome_browser_builds_finished_check,
  ADD CONSTRAINT genome_browser_builds_finished_check CHECK (
    CASE WHEN status IN ('ready', 'withdrawn') THEN
      num_nulls(gene_count, ready_at) = 0 AND gene_count >= 1
    ELSE
      num_nonnulls(gene_count, ready_at) = 0
    END
  ),
  -- Only a withdrawn build has a reason and a time, and the reason is not blank.
  DROP CONSTRAINT IF EXISTS genome_browser_builds_withdrawn_check,
  ADD CONSTRAINT genome_browser_builds_withdrawn_check CHECK (
    CASE WHEN status = 'withdrawn' THEN
      num_nulls(withdrawn_reason, withdrawn_at) = 0 AND btrim(withdrawn_reason) <> ''
      AND length(withdrawn_reason) <= 1000
    ELSE
      num_nonnulls(withdrawn_reason, withdrawn_at) = 0
    END
  );

ALTER TABLE public.genome_browser_objects
  DROP CONSTRAINT IF EXISTS genome_browser_objects_kind_check,
  ADD CONSTRAINT genome_browser_objects_kind_check
    CHECK (kind IN ('fasta', 'fai', 'gzi', 'gff', 'tbi')),
  DROP CONSTRAINT IF EXISTS genome_browser_objects_sha256_check,
  ADD CONSTRAINT genome_browser_objects_sha256_check CHECK (sha256 ~ '^[0-9a-f]{64}$'),
  DROP CONSTRAINT IF EXISTS genome_browser_objects_bytes_check,
  ADD CONSTRAINT genome_browser_objects_bytes_check CHECK (bytes > 0),
  DROP CONSTRAINT IF EXISTS genome_browser_objects_recorded_check,
  ADD CONSTRAINT genome_browser_objects_recorded_check CHECK (num_nulls(sha256, bytes) IN (0, 2));

ALTER TABLE public.genome_genes
  DROP CONSTRAINT IF EXISTS genome_genes_gene_id_check,
  ADD CONSTRAINT genome_genes_gene_id_check
    CHECK (btrim(gene_id) <> '' AND length(gene_id) <= 200),
  DROP CONSTRAINT IF EXISTS genome_genes_gene_name_check,
  ADD CONSTRAINT genome_genes_gene_name_check CHECK (length(gene_name) <= 200),
  DROP CONSTRAINT IF EXISTS genome_genes_seqid_check,
  ADD CONSTRAINT genome_genes_seqid_check CHECK (btrim(seqid) <> '' AND length(seqid) <= 200),
  DROP CONSTRAINT IF EXISTS genome_genes_span_check,
  ADD CONSTRAINT genome_genes_span_check CHECK (gene_start >= 1 AND gene_end >= gene_start),
  DROP CONSTRAINT IF EXISTS genome_genes_strand_check,
  ADD CONSTRAINT genome_genes_strand_check CHECK (strand IN ('+', '-', '.'));

-- 4. What may change -----------------------------------------------------------------------

-- A new build gets its version's next number, starts as uploading, and only for a ready
-- version, whoever inserts it.
CREATE OR REPLACE FUNCTION public.genome_browser_builds_number()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_status TEXT;
BEGIN
    IF NEW.status IS DISTINCT FROM 'uploading' THEN
        RAISE EXCEPTION 'a browser build starts as uploading' USING ERRCODE = '55000';
    END IF;
    -- The version's row lock numbers concurrent builds of one version one after another.
    SELECT v.status INTO v_status
      FROM public.genome_reference_versions v WHERE v.id = NEW.version_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'no genome version %', NEW.version_id USING ERRCODE = '23503';
    END IF;
    IF v_status <> 'ready' THEN
        RAISE EXCEPTION 'genome version % is %, not ready', NEW.version_id, v_status
            USING ERRCODE = '55000';
    END IF;
    SELECT coalesce(max(b.build), 0) + 1 INTO NEW.build
      FROM public.genome_browser_builds b WHERE b.version_id = NEW.version_id;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS genome_browser_builds_number ON public.genome_browser_builds;
CREATE TRIGGER genome_browser_builds_number
    BEFORE INSERT ON public.genome_browser_builds
    FOR EACH ROW EXECUTE FUNCTION public.genome_browser_builds_number();

-- A build's identity never changes. Its gene count and ready_at are set once, when it is
-- finished. Status moves only uploading -> ready | abandoned and ready -> withdrawn. A ready
-- or withdrawn build cannot be deleted.
CREATE OR REPLACE FUNCTION public.genome_browser_builds_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status IN ('ready', 'withdrawn') THEN
            RAISE EXCEPTION 'browser build % is %; withdraw it instead of deleting it',
                OLD.id, OLD.status USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.version_id IS DISTINCT FROM OLD.version_id
       OR NEW.build IS DISTINCT FROM OLD.build
       OR NEW.tool_versions IS DISTINCT FROM OLD.tool_versions
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'a browser build''s identity cannot change' USING ERRCODE = '55000';
    END IF;

    IF OLD.status <> 'uploading' AND (
        NEW.gene_count IS DISTINCT FROM OLD.gene_count
        OR NEW.ready_at IS DISTINCT FROM OLD.ready_at
    ) THEN
        RAISE EXCEPTION 'browser build % is %; it cannot change', OLD.id, OLD.status
            USING ERRCODE = '55000';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status AND (OLD.status, NEW.status) NOT IN (
        ('uploading', 'ready'), ('uploading', 'abandoned'), ('ready', 'withdrawn')
    ) THEN
        RAISE EXCEPTION 'browser build % cannot go from % to %', OLD.id, OLD.status, NEW.status
            USING ERRCODE = '55000';
    END IF;

    IF NEW.status = 'withdrawn' AND OLD.status = 'ready' THEN
        NEW.withdrawn_at := now();
    ELSIF NEW.withdrawn_reason IS DISTINCT FROM OLD.withdrawn_reason
          OR NEW.withdrawn_at IS DISTINCT FROM OLD.withdrawn_at THEN
        RAISE EXCEPTION 'a withdrawal is recorded only when a ready build is withdrawn'
            USING ERRCODE = '55000';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS genome_browser_builds_guard ON public.genome_browser_builds;
CREATE TRIGGER genome_browser_builds_guard
    BEFORE UPDATE OR DELETE ON public.genome_browser_builds
    FOR EACH ROW EXECUTE FUNCTION public.genome_browser_builds_guard();

-- A build's file and gene rows are added, changed or removed only while it is uploading. A
-- file's kind and path never change, and its checksum and size are set once.
CREATE OR REPLACE FUNCTION public.genome_browser_rows_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_build_id BIGINT := CASE WHEN TG_OP = 'INSERT' THEN NEW.build_id ELSE OLD.build_id END;
    v_status TEXT;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.build_id IS DISTINCT FROM OLD.build_id THEN
        RAISE EXCEPTION 'a row cannot move to another browser build' USING ERRCODE = '55000';
    END IF;
    SELECT b.status INTO v_status FROM public.genome_browser_builds b WHERE b.id = v_build_id;
    IF v_status IS DISTINCT FROM 'uploading' THEN
        RAISE EXCEPTION 'browser build % is %; its % cannot change', v_build_id,
            coalesce(v_status, 'missing'), TG_TABLE_NAME USING ERRCODE = '55000';
    END IF;
    -- Nested: NEW.kind exists only on genome_browser_objects.
    IF TG_TABLE_NAME = 'genome_browser_objects' AND TG_OP = 'UPDATE' THEN
        IF NEW.kind IS DISTINCT FROM OLD.kind OR NEW.path IS DISTINCT FROM OLD.path
           OR OLD.sha256 IS NOT NULL OR OLD.bytes IS NOT NULL THEN
            RAISE EXCEPTION 'a browser file''s path is fixed and its checksum is set once'
                USING ERRCODE = '55000';
        END IF;
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS genome_browser_objects_guard ON public.genome_browser_objects;
CREATE TRIGGER genome_browser_objects_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.genome_browser_objects
    FOR EACH ROW EXECUTE FUNCTION public.genome_browser_rows_guard();

DROP TRIGGER IF EXISTS genome_genes_guard ON public.genome_genes;
CREATE TRIGGER genome_genes_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.genome_genes
    FOR EACH ROW EXECUTE FUNCTION public.genome_browser_rows_guard();

-- 5. Gene positions of ready builds ----------------------------------------------------------

-- What gene search and single-cell links read: unfinished and withdrawn builds are left out.
CREATE OR REPLACE VIEW public.genome_gene_positions
WITH (security_invoker = true) AS
SELECT b.version_id, g.build_id, g.gene_id, g.gene_name, g.seqid, g.gene_start, g.gene_end,
       g.strand
FROM public.genome_genes g
JOIN public.genome_browser_builds b ON b.id = g.build_id
WHERE b.status = 'ready';

-- 6. Access --------------------------------------------------------------------------------

ALTER TABLE public.genome_browser_builds ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.genome_browser_objects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.genome_genes ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  v_table TEXT;
BEGIN
  FOREACH v_table IN ARRAY ARRAY['genome_browser_builds', 'genome_browser_objects', 'genome_genes']
  LOOP
    EXECUTE format('DROP POLICY IF EXISTS admin_all_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY admin_all_%1$s ON public.%1$I FOR ALL TO bloom_admin USING (true) WITH CHECK (true)',
      v_table
    );
    EXECUTE format('DROP POLICY IF EXISTS user_read_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY user_read_%1$s ON public.%1$I FOR SELECT TO bloom_user USING (true)', v_table
    );
    EXECUTE format('DROP POLICY IF EXISTS agent_read_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY agent_read_%1$s ON public.%1$I FOR SELECT TO bloom_agent USING (true)', v_table
    );
    EXECUTE format('DROP POLICY IF EXISTS workflows_read_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY workflows_read_%1$s ON public.%1$I FOR SELECT TO bloom_workflows USING (true)',
      v_table
    );

    -- Read for bloom_user (and so bloom_writer), bloom_agent and bloom_workflows; full access for
    -- bloom_admin. Writers change rows only through the build functions.
    EXECUTE format(
      'REVOKE ALL ON public.%I FROM anon, authenticated, bloom_user, bloom_agent, bloom_writer, bloom_workflows',
      v_table
    );
    EXECUTE format('REVOKE UPDATE, DELETE, TRUNCATE ON public.%I FROM service_role', v_table);
    EXECUTE format('GRANT SELECT ON public.%I TO bloom_user, bloom_agent, bloom_workflows', v_table);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO bloom_admin', v_table);
  END LOOP;
END
$$;

REVOKE ALL ON public.genome_gene_positions
    FROM anon, authenticated, bloom_user, bloom_agent, bloom_writer, bloom_workflows;
GRANT SELECT ON public.genome_gene_positions
    TO bloom_user, bloom_agent, bloom_workflows, bloom_admin;

REVOKE EXECUTE ON FUNCTION public.genome_browser_builds_number() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.genome_browser_builds_guard() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.genome_browser_rows_guard() FROM PUBLIC, anon, authenticated;

COMMIT;
