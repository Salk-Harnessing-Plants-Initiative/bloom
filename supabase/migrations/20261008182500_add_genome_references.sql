-- 20261008182500_add_genome_references.sql
--
-- Reference genomes for the Cell Ranger workflow, with numbered versions. A genome belongs to
-- a species; each version is one gzipped FASTA and one gzipped GTF in the genome-references
-- bucket (added by 20261008182600), with their SHA-256 and size. A version is uploading, then
-- ready or abandoned; an admin can withdraw a ready one, with a reason. Version numbers are
-- never reused, and a finished version's files and checksums never change.
-- Forward-only; rollback in supabase/rollbacks/.

BEGIN;

-- 1. Tables --------------------------------------------------------------------------------

-- Lowercase letters, digits, '.', '_' or '-', at most 64, with no '__' and no '.v<N>' ending,
-- which is how a version of a genome is written.
CREATE OR REPLACE FUNCTION public.genome_name_ok(p_name TEXT)
RETURNS BOOLEAN
LANGUAGE sql
IMMUTABLE
SET search_path = pg_catalog
AS $$
    SELECT p_name ~ '^[a-z0-9][a-z0-9._-]{0,63}$' AND p_name !~ '__' AND p_name !~ '\.v[0-9]+$';
$$;

CREATE TABLE IF NOT EXISTS public.genome_references (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    -- The storage folder name.
    name TEXT NOT NULL,
    species_id BIGINT NOT NULL,
    description TEXT,
    -- The number the next version gets; only ever goes up.
    next_version INTEGER NOT NULL DEFAULT 1,
    created_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.genome_reference_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    genome_id BIGINT NOT NULL,
    version INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'uploading',
    -- Object names in the genome-references bucket, set from the genome and version.
    fasta_path TEXT NOT NULL,
    gtf_path TEXT NOT NULL,
    -- Of the gzipped bytes stored; set when the upload is finished.
    fasta_sha256 TEXT,
    fasta_bytes BIGINT,
    gtf_sha256 TEXT,
    gtf_bytes BIGINT,
    -- Where the files came from, e.g. TAIR10 / Araport11 and the download page.
    assembly TEXT,
    annotation TEXT,
    source_url TEXT,
    notes TEXT,
    created_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ready_at TIMESTAMPTZ,
    withdrawn_reason TEXT,
    withdrawn_at TIMESTAMPTZ
);

-- 2. Keys ----------------------------------------------------------------------------------

