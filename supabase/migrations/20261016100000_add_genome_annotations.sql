-- 20261016100000_add_genome_annotations.sql
--
-- What each gene of a genome version does. An annotation build is one source's annotation of
-- one genome version: TAIR's curated GO (tair-go), eggNOG-mapper (eggnog: GO, KEGG orthologs
-- and pathways, gene names and descriptions) or Mercator4 (mercator: MapMan bins). It records
-- the tool and database versions used, and holds gene -> term rows keyed by the genome's own
-- gene IDs, plus a name and description per gene. Term names are shared in functional_terms.
-- A build is uploading, then ready or abandoned; an admin can withdraw a ready one, and a new
-- build of the same version and source can then be made. A ready build never changes.
-- The upload functions are added by 20261016100100.
-- Forward-only; rollback in supabase/rollbacks/.

BEGIN;

SET LOCAL lock_timeout = '5s';

-- 1. Tables --------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.genome_annotation_builds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    version_id BIGINT NOT NULL,
    source TEXT NOT NULL,
    -- Numbered per version and source, from 1.
    build INTEGER NOT NULL,
    status TEXT NOT NULL DEFAULT 'uploading',
    -- The tools and databases used, e.g. {"eggnog_mapper": "2.1.13", "eggnog_db": "5.0.2"}.
    tool_versions JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Set when the build is finished.
    gene_count INTEGER,
    term_count BIGINT,
    created_by UUID NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ready_at TIMESTAMPTZ,
    withdrawn_reason TEXT,
    withdrawn_at TIMESTAMPTZ
);

-- One row per term, shared by every build: GO terms with their namespace, KEGG pathways and
-- orthologs, MapMan bins.
CREATE TABLE IF NOT EXISTS public.functional_terms (
    kind TEXT NOT NULL,
    term_id TEXT NOT NULL,
    name TEXT NOT NULL,
    namespace TEXT
);

-- A gene's terms in one build. GO terms include their ancestors; direct says whether the
-- source gave the term itself.
CREATE TABLE IF NOT EXISTS public.genome_gene_terms (
    build_id BIGINT NOT NULL,
    gene_id TEXT NOT NULL,
    kind TEXT NOT NULL,
    term_id TEXT NOT NULL,
    direct BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS public.genome_gene_descriptions (
    build_id BIGINT NOT NULL,
    gene_id TEXT NOT NULL,
    gene_name TEXT,
    description TEXT
);

-- 2. Keys ----------------------------------------------------------------------------------

DO $$
DECLARE
  v_key RECORD;
  existing TEXT;
BEGIN
  FOR v_key IN
    SELECT * FROM (VALUES
      ('genome_annotation_builds', 'genome_annotation_builds_pkey', 'PRIMARY KEY (id)'),
      ('genome_annotation_builds', 'genome_annotation_builds_version_source_build_key',
       'UNIQUE (version_id, source, build)'),
      ('functional_terms', 'functional_terms_pkey', 'PRIMARY KEY (kind, term_id)'),
      ('genome_gene_terms', 'genome_gene_terms_pkey', 'PRIMARY KEY (build_id, kind, term_id, gene_id)'),
      ('genome_gene_descriptions', 'genome_gene_descriptions_pkey', 'PRIMARY KEY (build_id, gene_id)')
    ) AS k(tbl, name, def)
  LOOP
    SELECT pg_get_constraintdef(c.oid) INTO existing
      FROM pg_constraint c
     WHERE c.conname = v_key.name AND c.conrelid = format('public.%I', v_key.tbl)::regclass;
    IF existing IS NULL THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I %s', v_key.tbl, v_key.name, v_key.def);
    ELSIF existing <> v_key.def THEN
      RAISE EXCEPTION '% is %, expected %', v_key.name, existing, v_key.def;
    END IF;
  END LOOP;
END $$;

DO $$
DECLARE
  v_fk RECORD;
BEGIN
  FOR v_fk IN
    SELECT * FROM (VALUES
      ('genome_annotation_builds', 'genome_annotation_builds_version_id_fkey',
       'FOREIGN KEY (version_id) REFERENCES public.genome_reference_versions(id)'),
      ('genome_gene_terms', 'genome_gene_terms_build_id_fkey',
       'FOREIGN KEY (build_id) REFERENCES public.genome_annotation_builds(id)'),
      ('genome_gene_terms', 'genome_gene_terms_term_fkey',
       'FOREIGN KEY (kind, term_id) REFERENCES public.functional_terms(kind, term_id)'),
      ('genome_gene_descriptions', 'genome_gene_descriptions_build_id_fkey',
       'FOREIGN KEY (build_id) REFERENCES public.genome_annotation_builds(id)')
    ) AS k(tbl, name, def)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_constraint c
       WHERE c.conname = v_fk.name AND c.conrelid = format('public.%I', v_fk.tbl)::regclass
    ) THEN
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I %s', v_fk.tbl, v_fk.name, v_fk.def);
    END IF;
  END LOOP;
END $$;

-- At most one build of a version and source is being made or in use.
CREATE UNIQUE INDEX IF NOT EXISTS genome_annotation_builds_one_live
    ON public.genome_annotation_builds (version_id, source) WHERE status IN ('uploading', 'ready');

-- Enrichment reads a build's genes per term; gene pages read a gene's terms.
CREATE INDEX IF NOT EXISTS genome_gene_terms_build_gene_idx
    ON public.genome_gene_terms (build_id, gene_id);

-- 3. Checks --------------------------------------------------------------------------------

ALTER TABLE public.genome_annotation_builds
  DROP CONSTRAINT IF EXISTS genome_annotation_builds_source_check,
  ADD CONSTRAINT genome_annotation_builds_source_check
    CHECK (source IN ('tair-go', 'eggnog', 'mercator')),
  DROP CONSTRAINT IF EXISTS genome_annotation_builds_build_check,
  ADD CONSTRAINT genome_annotation_builds_build_check CHECK (build >= 1),
  DROP CONSTRAINT IF EXISTS genome_annotation_builds_status_check,
  ADD CONSTRAINT genome_annotation_builds_status_check
    CHECK (status IN ('uploading', 'ready', 'abandoned', 'withdrawn')),
  DROP CONSTRAINT IF EXISTS genome_annotation_builds_tool_versions_check,
  ADD CONSTRAINT genome_annotation_builds_tool_versions_check CHECK (
    jsonb_typeof(tool_versions) = 'object' AND length(tool_versions::text) <= 2000
  ),
  -- A ready or withdrawn build has its counts and ready_at; any other has none of them.
  DROP CONSTRAINT IF EXISTS genome_annotation_builds_finished_check,
  ADD CONSTRAINT genome_annotation_builds_finished_check CHECK (
    CASE WHEN status IN ('ready', 'withdrawn') THEN
      num_nulls(gene_count, term_count, ready_at) = 0 AND gene_count >= 1 AND term_count >= 1
    ELSE
      num_nonnulls(gene_count, term_count, ready_at) = 0
    END
  ),
  DROP CONSTRAINT IF EXISTS genome_annotation_builds_withdrawn_check,
  ADD CONSTRAINT genome_annotation_builds_withdrawn_check CHECK (
    CASE WHEN status = 'withdrawn' THEN
      num_nulls(withdrawn_reason, withdrawn_at) = 0 AND btrim(withdrawn_reason) <> ''
      AND length(withdrawn_reason) <= 1000
    ELSE
      num_nonnulls(withdrawn_reason, withdrawn_at) = 0
    END
  );

ALTER TABLE public.functional_terms
  DROP CONSTRAINT IF EXISTS functional_terms_kind_check,
  ADD CONSTRAINT functional_terms_kind_check
    CHECK (kind IN ('go', 'kegg_pathway', 'kegg_ko', 'mapman')),
  DROP CONSTRAINT IF EXISTS functional_terms_term_id_check,
  ADD CONSTRAINT functional_terms_term_id_check
    CHECK (btrim(term_id) <> '' AND length(term_id) <= 100),
  DROP CONSTRAINT IF EXISTS functional_terms_name_check,
  ADD CONSTRAINT functional_terms_name_check CHECK (btrim(name) <> '' AND length(name) <= 500),
  -- GO terms belong to one namespace; other kinds have none.
  DROP CONSTRAINT IF EXISTS functional_terms_namespace_check,
  ADD CONSTRAINT functional_terms_namespace_check CHECK (
    CASE WHEN kind = 'go' THEN coalesce(namespace IN ('BP', 'MF', 'CC'), false)
    ELSE namespace IS NULL END
  );

ALTER TABLE public.genome_gene_terms
  DROP CONSTRAINT IF EXISTS genome_gene_terms_gene_id_check,
  ADD CONSTRAINT genome_gene_terms_gene_id_check
    CHECK (btrim(gene_id) <> '' AND length(gene_id) <= 200);

ALTER TABLE public.genome_gene_descriptions
  DROP CONSTRAINT IF EXISTS genome_gene_descriptions_gene_id_check,
  ADD CONSTRAINT genome_gene_descriptions_gene_id_check
    CHECK (btrim(gene_id) <> '' AND length(gene_id) <= 200),
  DROP CONSTRAINT IF EXISTS genome_gene_descriptions_text_check,
  ADD CONSTRAINT genome_gene_descriptions_text_check CHECK (
    num_nonnulls(gene_name, description) >= 1
    AND length(gene_name) <= 200 AND length(description) <= 2000
  );

-- 4. What may change -----------------------------------------------------------------------

-- A new build gets its version and source's next number, starts as uploading, and only for a
-- ready version, whoever inserts it.
CREATE OR REPLACE FUNCTION public.genome_annotation_builds_number()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_status TEXT;
BEGIN
    IF NEW.status IS DISTINCT FROM 'uploading' THEN
        RAISE EXCEPTION 'an annotation build starts as uploading' USING ERRCODE = '55000';
    END IF;
    -- The version's row lock numbers concurrent builds of one version one after another.
    SELECT v.status INTO v_status
      FROM public.genome_reference_versions v WHERE v.id = NEW.version_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'no genome version %', NEW.version_id USING ERRCODE = '23503';
    END IF;
    IF v_status <> 'ready' THEN
        RAISE EXCEPTION 'genome version % is %, not ready', NEW.version_id, v_status
            USING ERRCODE = '55000';
    END IF;
    SELECT coalesce(max(b.build), 0) + 1 INTO NEW.build
      FROM public.genome_annotation_builds b
     WHERE b.version_id = NEW.version_id AND b.source = NEW.source;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS genome_annotation_builds_number ON public.genome_annotation_builds;
CREATE TRIGGER genome_annotation_builds_number
    BEFORE INSERT ON public.genome_annotation_builds
    FOR EACH ROW EXECUTE FUNCTION public.genome_annotation_builds_number();

-- A build's identity never changes. Its counts and ready_at are set once, when it is finished.
-- Status moves only uploading -> ready | abandoned and ready -> withdrawn. A ready or
-- withdrawn build cannot be deleted.
CREATE OR REPLACE FUNCTION public.genome_annotation_builds_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status IN ('ready', 'withdrawn') THEN
            RAISE EXCEPTION 'annotation build % is %; withdraw it instead of deleting it',
                OLD.id, OLD.status USING ERRCODE = '55000';
        END IF;
        RETURN OLD;
    END IF;

    IF NEW.id IS DISTINCT FROM OLD.id
       OR NEW.version_id IS DISTINCT FROM OLD.version_id
       OR NEW.source IS DISTINCT FROM OLD.source
       OR NEW.build IS DISTINCT FROM OLD.build
       OR NEW.tool_versions IS DISTINCT FROM OLD.tool_versions
       OR NEW.created_by IS DISTINCT FROM OLD.created_by
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'an annotation build''s identity cannot change' USING ERRCODE = '55000';
    END IF;

    IF OLD.status <> 'uploading' AND (
        NEW.gene_count IS DISTINCT FROM OLD.gene_count
        OR NEW.term_count IS DISTINCT FROM OLD.term_count
        OR NEW.ready_at IS DISTINCT FROM OLD.ready_at
    ) THEN
        RAISE EXCEPTION 'annotation build % is %; it cannot change', OLD.id, OLD.status
            USING ERRCODE = '55000';
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status AND (OLD.status, NEW.status) NOT IN (
        ('uploading', 'ready'), ('uploading', 'abandoned'), ('ready', 'withdrawn')
    ) THEN
        RAISE EXCEPTION 'annotation build % cannot go from % to %', OLD.id, OLD.status, NEW.status
            USING ERRCODE = '55000';
    END IF;

    IF NEW.status = 'withdrawn' AND OLD.status = 'ready' THEN
        NEW.withdrawn_at := now();
    ELSIF NEW.withdrawn_reason IS DISTINCT FROM OLD.withdrawn_reason
          OR NEW.withdrawn_at IS DISTINCT FROM OLD.withdrawn_at THEN
        RAISE EXCEPTION 'a withdrawal is recorded only when a ready build is withdrawn'
            USING ERRCODE = '55000';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS genome_annotation_builds_guard ON public.genome_annotation_builds;
CREATE TRIGGER genome_annotation_builds_guard
    BEFORE UPDATE OR DELETE ON public.genome_annotation_builds
    FOR EACH ROW EXECUTE FUNCTION public.genome_annotation_builds_guard();

-- A build's term and description rows are added, changed or removed only while it is
-- uploading, and never move to another build.
CREATE OR REPLACE FUNCTION public.genome_annotation_rows_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_build_id BIGINT := CASE WHEN TG_OP = 'INSERT' THEN NEW.build_id ELSE OLD.build_id END;
    v_status TEXT;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.build_id IS DISTINCT FROM OLD.build_id THEN
        RAISE EXCEPTION 'a row cannot move to another annotation build' USING ERRCODE = '55000';
    END IF;
    SELECT b.status INTO v_status FROM public.genome_annotation_builds b WHERE b.id = v_build_id;
    IF v_status IS DISTINCT FROM 'uploading' THEN
        RAISE EXCEPTION 'annotation build % is %; its % cannot change', v_build_id,
            coalesce(v_status, 'missing'), TG_TABLE_NAME USING ERRCODE = '55000';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

DROP TRIGGER IF EXISTS genome_gene_terms_guard ON public.genome_gene_terms;
CREATE TRIGGER genome_gene_terms_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.genome_gene_terms
    FOR EACH ROW EXECUTE FUNCTION public.genome_annotation_rows_guard();

DROP TRIGGER IF EXISTS genome_gene_descriptions_guard ON public.genome_gene_descriptions;
CREATE TRIGGER genome_gene_descriptions_guard
    BEFORE INSERT OR UPDATE OR DELETE ON public.genome_gene_descriptions
    FOR EACH ROW EXECUTE FUNCTION public.genome_annotation_rows_guard();

-- 5. Access --------------------------------------------------------------------------------

DO $$
DECLARE
  v_table TEXT;
BEGIN
  FOREACH v_table IN ARRAY ARRAY[
    'genome_annotation_builds', 'functional_terms', 'genome_gene_terms', 'genome_gene_descriptions'
  ] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', v_table);
    EXECUTE format('DROP POLICY IF EXISTS admin_all_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY admin_all_%1$s ON public.%1$I FOR ALL TO bloom_admin USING (true) WITH CHECK (true)',
      v_table
    );
    EXECUTE format('DROP POLICY IF EXISTS user_read_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY user_read_%1$s ON public.%1$I FOR SELECT TO bloom_user USING (true)', v_table
    );
    EXECUTE format('DROP POLICY IF EXISTS agent_read_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY agent_read_%1$s ON public.%1$I FOR SELECT TO bloom_agent USING (true)', v_table
    );
    EXECUTE format('DROP POLICY IF EXISTS workflows_read_%1$s ON public.%1$I', v_table);
    EXECUTE format(
      'CREATE POLICY workflows_read_%1$s ON public.%1$I FOR SELECT TO bloom_workflows USING (true)',
      v_table
    );

    -- Read for bloom_user (and so bloom_writer), bloom_agent and bloom_workflows; full access for
    -- bloom_admin. Writers and the pipeline change rows only through the upload functions.
    EXECUTE format(
      'REVOKE ALL ON public.%I FROM anon, authenticated, bloom_user, bloom_agent, bloom_writer, bloom_workflows',
      v_table
    );
    EXECUTE format('REVOKE UPDATE, DELETE, TRUNCATE ON public.%I FROM service_role', v_table);
    EXECUTE format('GRANT SELECT ON public.%I TO bloom_user, bloom_agent, bloom_workflows', v_table);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO bloom_admin', v_table);
  END LOOP;
END
$$;

REVOKE EXECUTE ON FUNCTION public.genome_annotation_builds_number() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.genome_annotation_builds_guard() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.genome_annotation_rows_guard() FROM PUBLIC, anon, authenticated;

COMMIT;
