"""Pixel-level rendering regression tests for the 5 sleap_roots plotting tools (#713).

`test_viz_tools.py` only ever asserted `.is_file()` on a generated PNG -- a dependency
bump (matplotlib, Pillow, numpy) or a refactor that silently changes color mapping, plot
geometry, or layout would ship with every existing assertion still green. This file closes
that gap by comparing each tool's real output against a committed baseline PNG
(`tests/fixtures/plot_baselines/`, generated by `scripts/gen_plot_snapshots_golden.py`)
via `matplotlib.testing.compare.compare_images` -- matplotlib's own image-comparison
utility (used by its own test suite), available with **no new dependency**: Pillow, which
`compare_images` needs to load PNGs, is a hard transitive floor of both `matplotlib` and
`sleap-roots-analyze`, bloommcp's own main dependencies (not an incidental extra), so it
is not at risk of quietly disappearing from the venv.

Tolerance (`_TOL`): `compare_images` scores a pair of images by RMS pixel difference (0 =
bit-identical). Some noise is expected even for a correct render: FreeType hinting differs
slightly across OS/font-stack combinations. **The baselines here were generated on
macOS**, not on Linux (see `plot_baselines/MANIFEST.json` and design.md Decision 3 — Docker
was unavailable to produce a Linux-rendered baseline matching the `python-audit` CI job's
`ubuntu-latest` runner at authoring time), so this test's *first* real cross-platform
comparison is CI's own run, not this docstring's say-so. `_TOL` was picked from a real,
reproducible measurement, not guessed: uniformly dimming the `histograms` baseline by 2%
(`PIL.ImageEnhance.Brightness(0.98)`) against itself scores RMS≈5.6; 5% scores RMS≈12.2;
10% scores RMS≈24.4 (see `test_tolerance_catches_a_real_regression` below, which
reproduces the 10% case live rather than hardcoding these numbers). `_TOL = 15` sits above
the 5%-dim noise floor (leaving headroom for legitimate cross-platform hinting noise,
which manifests as far subtler pixel deltas than a uniform intensity shift) and
comfortably below the 10% case a real color-rendering regression would plausibly produce.
If CI's first real cross-platform run shows the genuine hinting-noise RMS is closer to
`_TOL` than expected, that is the authoritative signal to revisit this constant or
regenerate the baselines from a Linux run -- see `scripts/gen_plot_snapshots_golden.py`'s
module docstring.

Known limitation -- localized regressions: RMS is a whole-image average, so a spatially
small miscoloring is diluted across every unaffected pixel. Measured directly against the
`heritability_bar` baseline (single fully-recolored rectangle vs. the original): a region
covering ~1.5% of the image area scores RMS≈14.4 (would NOT be caught at `_TOL=15`); ~2%
scores RMS≈16.7 (would be caught). A single bar in an ~18-trait bar chart is comfortably
above that floor, but a single cell in a large correlation-matrix heatmap could plausibly
fall under it. This is an accepted tradeoff of a whole-image, "lightweight" tolerance
check (the issue's own word) rather than a per-region diff -- catching every possible
single-element miscoloring would need a heavier-weight structural comparison, which is
out of scope here.

Scope: the 5 dedicated plotting tools only (matching `test_viz_tools.py`'s existing
`_TOOLS` list) -- the optional plot keys `pca_analysis`/`umap_analysis`/`clustering` can
also emit (`create_pca_biplot`, `create_cluster_scatter_pca`, etc.) are a deliberate
non-goal here; see proposal.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest
from matplotlib.testing.compare import compare_images
from PIL import Image, ImageDraw, ImageEnhance

from bloom_mcp.sections.sleap_roots.analysis import (
    plot_correlation_matrix as plot_correlation_matrix_mod,
    plot_heritability_bar as plot_heritability_bar_mod,
    plot_trait_boxplots as plot_trait_boxplots_mod,
    plot_trait_histograms as plot_trait_histograms_mod,
    plot_variance_decomposition as plot_variance_decomposition_mod,
)

_BASELINES = Path(__file__).resolve().parents[1] / "fixtures" / "plot_baselines"
_EXPERIMENT = "turface_19.csv"

# See module docstring for how this was derived.
_TOL = 15

# (label, tool module, tool fn name, produced PNG name, baseline PNG name)
_SNAPSHOT_TOOLS = [
    (
        "histograms",
        plot_trait_histograms_mod,
        "plot_trait_histograms",
        "histograms_turface_19.png",
        "histograms_turface_19_baseline.png",
    ),
    (
        "boxplots",
        plot_trait_boxplots_mod,
        "plot_trait_boxplots",
        "boxplots_turface_19.png",
        "boxplots_turface_19_baseline.png",
    ),
    (
        "correlation_matrix",
        plot_correlation_matrix_mod,
        "plot_correlation_matrix",
        "correlation_matrix_turface_19.png",
        "correlation_matrix_turface_19_baseline.png",
    ),
    (
        "heritability_bar",
        plot_heritability_bar_mod,
        "plot_heritability_bar",
        "heritability_turface_19.png",
        "heritability_turface_19_baseline.png",
    ),
    (
        "variance_decomposition",
        plot_variance_decomposition_mod,
        "plot_variance_decomposition",
        "variance_decomposition_turface_19.png",
        "variance_decomposition_turface_19_baseline.png",
    ),
]
_IDS = [label for label, *_ in _SNAPSHOT_TOOLS]


@pytest.mark.parametrize(
    "_label,module,fn_name,produced_name,baseline_name", _SNAPSHOT_TOOLS, ids=_IDS
)
def test_plot_matches_baseline_within_tolerance(
    _label, module, fn_name, produced_name, baseline_name, viz_env
):
    fn = getattr(module, fn_name)
    result = fn(_EXPERIMENT)
    assert "Plot saved:" in result

    actual = viz_env / produced_name
    baseline = _BASELINES / baseline_name
    assert actual.is_file()
    assert baseline.is_file(), (
        f"missing baseline {baseline} -- run "
        "`uv run --frozen --extra test python scripts/gen_plot_snapshots_golden.py` to create it"
    )

    diff = _compare_or_fail(baseline, actual)
    assert diff is None, diff


def _compare_or_fail(baseline: Path, actual: Path):
    """`compare_images` raises `ImageComparisonFailure` (not a clean result) when the two
    PNGs differ in pixel dimensions -- e.g. if `bbox_inches="tight"` (`_viz_shared.save_plot`)
    produced a different canvas size on this platform than the baseline's, itself a
    plausible symptom of the same cross-platform font-hinting risk `_TOL` is calibrated
    against (design.md Decision 3). Convert that into the same actionable failure shape as
    an over-tolerance RMS, instead of letting a raw exception obscure the diagnosis.
    """
    try:
        return compare_images(str(baseline), str(actual), tol=_TOL)
    except Exception as exc:  # noqa: BLE001 -- re-raised as an actionable pytest failure
        pytest.fail(
            f"{exc}\n"
            "If this is a dimension mismatch (not an RMS-over-tolerance message), it may "
            "be a cross-platform bbox_inches='tight' canvas-size difference rather than a "
            "content regression -- see design.md Decision 3 before regenerating baselines."
        )


def test_tolerance_catches_a_real_regression(tmp_path):
    """`_TOL` must not be so loose it rubber-stamps a genuine rendering regression.

    Dims one real baseline by 10% (`PIL.ImageEnhance.Brightness(0.9)`) -- the same
    perturbation the module docstring cites as scoring RMS≈24.4, reproduced live here
    (not hardcoded) so this stays a real assertion against `compare_images`, not a pinned
    magic number. A uniform intensity shift is a stand-in for "a rendering regression
    large enough to matter", not a literal simulation of any specific known bug.
    """
    baseline = _BASELINES / "histograms_turface_19_baseline.png"
    dimmed = ImageEnhance.Brightness(Image.open(baseline)).enhance(0.9)
    perturbed = tmp_path / "dimmed.png"
    dimmed.save(perturbed)

    diff = compare_images(str(baseline), str(perturbed), tol=_TOL)
    assert diff is not None, (
        f"a 10%-dimmed baseline compared equal to itself -- _TOL={_TOL} is too loose "
        "to catch a real regression"
    )


def test_tolerance_catches_a_localized_regression(tmp_path):
    """A *global* dim (above) isn't the only regression shape worth proving `_TOL` catches
    -- a single mis-colored element (one bar, one heatmap cell) only touches part of the
    image, and RMS is a whole-image average (see module docstring's "Known limitation").
    Recolors ~2% of the `heritability_bar` baseline's area (empirically, this repo's
    measured floor above which such a regression clears `_TOL=15`; see the module
    docstring) and confirms it is still caught.
    """
    baseline = _BASELINES / "heritability_turface_19_baseline.png"
    img = Image.open(baseline).convert("RGB")
    w, h = img.size
    perturbed_img = img.copy()
    side = int((w * h * 0.02) ** 0.5)
    x0, y0 = w // 3, h // 3
    ImageDraw.Draw(perturbed_img).rectangle(
        [x0, y0, x0 + side, y0 + side], fill=(255, 165, 0)
    )
    perturbed = tmp_path / "localized.png"
    perturbed_img.save(perturbed)

    diff = compare_images(str(baseline), str(perturbed), tol=_TOL)
    assert diff is not None, (
        f"a ~2%-area recolored baseline compared equal to itself -- _TOL={_TOL} is too "
        "loose to catch even this deliberately-sized localized regression"
    )


def test_missing_baseline_fails_with_an_actionable_message(monkeypatch, viz_env):
    monkeypatch.setattr(sys.modules[__name__], "_BASELINES", viz_env / "no_such_dir")
    with pytest.raises(AssertionError, match="gen_plot_snapshots_golden"):
        test_plot_matches_baseline_within_tolerance(
            "histograms",
            plot_trait_histograms_mod,
            "plot_trait_histograms",
            "histograms_turface_19.png",
            "histograms_turface_19_baseline.png",
            viz_env,
        )
